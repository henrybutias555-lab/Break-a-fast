/* Builds api/dist/worker.mjs for Cloudflare Workers:
   menu/config data + core.js + a fetch() handler, in one ES module.
   Run: node api/build-worker.js */
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
const sandbox = { window: {} };
for (const f of ["js/config.js", "js/products.js", "js/events-data.js"]) vm.runInNewContext(fs.readFileSync(path.join(ROOT, f), "utf8"), sandbox);
const W = sandbox.window;
const data = {
  BAF_CONFIG: { ...W.BAF_CONFIG, apiBase: undefined },
  BAF_PRODUCTS: W.BAF_PRODUCTS,
  BAF_EVENT_GROUPS: W.BAF_EVENT_GROUPS,
  BAF_EVENT_MENU: W.BAF_EVENT_MENU,
  BAF_PICK_SOURCES: W.BAF_PICK_SOURCES
};

const core = fs.readFileSync(path.join(__dirname, "core.js"), "utf8");
const logo = (f) => "data:image/jpeg;base64," + fs.readFileSync(path.join(ROOT, "assets", "img", f)).toString("base64");
const LOGOS = { header: logo("logo-invoice.jpg"), watermark: logo("logo-watermark.jpg") };
const out = `// GENERATED by api/build-worker.js. Do not edit; edit core.js / the js/ data files instead.
import crypto from "node:crypto";
import { Buffer } from "node:buffer";
const W = ${JSON.stringify(data)};
const LOGOS = ${JSON.stringify(LOGOS)};
${core}
let app;
export default {
  async fetch(request, env, ctx) {
    if (!app) {
      if (!env.SIGNING_SECRET || env.SIGNING_SECRET.length < 32) return new Response("Server not configured", { status: 500 });
      app = createApp({
        SECRET: env.SIGNING_SECRET, ALERT_URL: env.ALERT_URL || "", ALERT_KEY: env.ALERT_KEY || "", OWNER_PIN: env.OWNER_PIN || "",
        ALLOWED_ORIGINS: (env.ALLOWED_ORIGINS || "https://break-a-fast.onrender.com").split(",").map((s) => s.trim()),
        W, crypto, Buffer, LOGOS
      });
    }
    const url = new URL(request.url);
    const bodyText = request.method === "POST" ? (await request.text()).slice(0, 20001) : "";
    const r = await app.handle({
      method: request.method, pathname: url.pathname, origin: request.headers.get("origin"),
      base: url.origin, ip: request.headers.get("cf-connecting-ip") || "?", bodyText
    });
    for (const w of r.waits || []) ctx.waitUntil(Promise.resolve(w).catch(() => {}));
    return new Response(r.status === 204 ? null : r.body, {
      status: r.status,
      headers: { "Content-Type": r.type + "; charset=utf-8", "X-Content-Type-Options": "nosniff", "Cache-Control": "no-store", ...r.headers }
    });
  }
};
`;
fs.mkdirSync(path.join(__dirname, "dist"), { recursive: true });
fs.writeFileSync(path.join(__dirname, "dist", "worker.mjs"), out);
console.log("built api/dist/worker.mjs", out.length, "bytes");
